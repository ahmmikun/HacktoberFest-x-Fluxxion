import { Router } from "express";
import rateLimit from "express-rate-limit";
import { CreateIssueRequestSchema, type AuditFinding, type AuditResult, type CreateIssueResponse } from "@reposage/shared";
import { getSession } from "../services/auditStore.js";
import { GhCliBridge } from "../services/ghBridge.js";
import { logger } from "../utils/logger.js";
import { asyncHandler, HttpError, UUID_REGEX } from "../utils/http.js";

export const actionsRouter = Router();

const issueLimiter = rateLimit({ windowMs: 60_000, limit: 10, standardHeaders: "draft-7", legacyHeaders: false });

/** Issue body is built server-side from the stored, verified finding — clients cannot inject content. */
function issueBody(audit: AuditResult, f: AuditFinding, modelId: string): string {
  const refs = f.evidenceRefs
    .map((r) => `- \`${r.filePath}\`${r.checkId ? ` (check \`${r.checkId}\`)` : ""}${r.snippetQuote ? ` — "${r.snippetQuote.replace(/[\r\n]+/g, " ")}"` : ""}`)
    .join("\n");
  return [
    `**Severity:** ${f.severity} · **Priority:** P${f.suggestedPriority} · **Category:** ${f.category}`,
    "",
    "### Impact",
    f.impact,
    "",
    "### Remediation steps",
    ...f.remediationSteps.map((s, i) => `${i + 1}. ${s}`),
    "",
    "### Evidence (verified against the repository tree)",
    refs,
    "",
    "---",
    `_Generated by RepoSage · model \`${modelId}\` · audit \`${audit.auditId}\` · commit \`${audit.metadata?.headSha ?? "n/a"}\` · manifest \`${audit.manifestSha256 ?? "n/a"}\`_`,
  ].join("\n");
}

/** POST /api/v1/actions/create-issue — runs `gh issue create` for a VERIFIED finding (FR-ACT-03). */
actionsRouter.post(
  "/create-issue",
  issueLimiter,
  asyncHandler(async (req, res) => {
    const parsed = CreateIssueRequestSchema.safeParse(req.body);
    if (!parsed.success) {
      throw new HttpError(400, "Invalid request. Explicit confirmation (confirm: true) is required.", parsed.error.flatten().fieldErrors);
    }
    const { auditId, modelRuntime, findingId } = parsed.data;
    if (!UUID_REGEX.test(auditId)) throw new HttpError(400, "Invalid audit id.");

    const session = getSession(auditId);
    if (!session) throw new HttpError(404, "Audit not found or expired.");

    const run = session.result.models.find((m) => m.runtime === modelRuntime);
    const finding = run?.verifiedFindings.find((f) => f.id === findingId);
    if (!run || !finding) throw new HttpError(404, "Verified finding not found. Unverified claims cannot be filed as issues.");

    const dedupeKey = `${modelRuntime}:${findingId}`;
    const existing = session.createdIssues.get(dedupeKey);
    if (existing) {
      res.json({ issueUrl: existing } satisfies CreateIssueResponse);
      return;
    }

    try {
      const { issueUrl } = await GhCliBridge.createRemediationIssue(session.result.repo, finding.title, issueBody(session.result, finding, run.modelId));
      session.createdIssues.set(dedupeKey, issueUrl);
      logger.info(`Created issue for ${session.result.repo}: ${issueUrl}`);
      res.status(201).json({ issueUrl } satisfies CreateIssueResponse);
    } catch (err) {
      throw new HttpError(502, (err as Error).message);
    }
  }),
);
